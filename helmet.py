"""
AstroHealth - helmet HUD (visor display).

Designed to be read at a glance without distracting from the video. No backgrounds: everything is
transparent and the texts have a dark shadow so they can be read over bright or dark video.
- Top left: who you are (or who you are viewing).
- Top center: UTC time and link with the ship, discreet.
- Top right: large overall state (with the name of whoever is in alert).
- Below, on the right: iPhone-style notifications (name and problem).
- Left: pulse circle (the ring changes color) and VITALS panel (HR, SpO₂, TEMP,
  PRES) with their range and value; critical values are marked in red.
- Bottom: only the shortcuts that are useful at that moment.
Same alert rules as the wristband (it inherits from it).

Controls (designed for use with gloves): ◀ ▶ switch crew member, Home = back to you,
Enter = ACKNOWLEDGED, A = I'M ON MY WAY, V = view the data of the crew member in emergency.

BACKGROUND VIDEO (optional): put a "fondo.mp4" file in this folder and install
    pip install opencv-python pillow
If the video is missing or those libraries are not installed, space and the Moon are drawn.

Synthetic data · Illustrative rules · Do not use for real medical decisions.
"""
import os
import math
import random
import time
import tkinter as tk

from wristband import Wristband, OK, CAUTION, ALERT, NO_SIGNAL, INVALID, GREEN, FONT_FAMILY

# Scale of the helmet being drawn (1.0 = full size). Several helmets can be open at the same time
# at a reduced size ("All helmets" button); drawing is done in 1120×640 coordinates and scaled at
# the end, together with the fonts.
_SCALE = [1.0]


def f(size, weight="normal"):
    return (FONT_FAMILY, max(5, round(size * _SCALE[0])), weight)
from simulation import IND, SIGNAL, format_value, protocol_for

try:                                    # optional libraries for the background video
    import cv2
    from PIL import Image, ImageTk
    _MISSING = None
except ImportError as _e:
    cv2 = None
    _MISSING = _e.name                    # "cv2" or "PIL"

_FOLDER = os.path.dirname(os.path.abspath(__file__))
BACKGROUND_VIDEO = os.path.join(_FOLDER, "fondo.mp4")
# One video per crew member, in crew order (1st = Alex, 2nd = Sofía, ...).
# Switching person switches the video, and it does NOT start over: each video keeps running
# even when it is not being watched (like each person's helmet camera).
VIDEOS_PER_PERSON = ["fondo.mp4", "video2.mp4", "video3.mp4", "video4.mp4", "video5.mp4"]
VIDEO_BRIGHTNESS = 0.6        # 1.0 = original video; lower = darker (data is easier to read)

# Only 3 state colors: light blue (good), amber (caution) and red (alert / no signal)
HUD = "#8FE6FF"
HUD_DIM = "#5E9BB5"
WHITE = "#F0FAFF"
AMBER = "#FFC24A"
RED = "#FF4545"
BLOCK_BG = "#02060D"
COLOR_HUD = {OK: HUD, CAUTION: AMBER, ALERT: RED, NO_SIGNAL: RED, INVALID: RED}
HUD_WORD = {OK: "IN RANGE", CAUTION: "CAUTION", ALERT: "RED ALERT", NO_SIGNAL: "NO SIGNAL"}

VITALS = ["hr", "spo2", "temp", "sbp"]
SHORT = {"hr": "HR", "spo2": "SpO₂", "temp": "TEMP", "sbp": "PRES", "glu": "GLU",
         "sleep": "SLEEP", "exercise": "EXERC", "rad": "RAD"}


class Helmet(Wristband):
    WIDTH, HEIGHT = 1120, 640
    NAME = "Helmet · HUD"
    RESIZABLE = False

    def _build_ui(self):
        """The helmet uses a single fixed-size canvas (no scrolling)."""
        self.cv = tk.Canvas(self, width=self.real_width, height=self.real_height, bg="#02060D", highlightthickness=0)
        self.cv.pack()
        self._canvases = [self.cv]

    def __init__(self, master, mission, owner, db_=None, on_close=None, routines=None, hud_scale=1.0):
        self.hud_scale = max(0.3, min(1.0, float(hud_scale)))
        self.real_width = round(self.WIDTH * self.hud_scale)
        self.real_height = round(self.HEIGHT * self.hud_scale)
        rng = random.Random(7)
        self.stars = [(rng.uniform(0, self.WIDTH), rng.uniform(0, self.HEIGHT * 0.7),
                           rng.choice((1, 1, 1.5, 2))) for _ in range(160)]
        self._banner_key = None
        self._banner_t0 = 0.0
        # tank notices: generated by the ENGINE (simulation.Mission._check_support) even when the helmet
        # is closed; the helmet only shows them. When it opens, the ones still current are shown.
        self._support_cursor = len(mission.support_notices)
        self._current_shown = False
        self._video = None              # video of the person being viewed (or None)
        self._videos = {}               # file -> {"cap", "fps", "n", "pos"}  (opened when used)
        self._video_t0 = time.monotonic()   # common clock: all videos advance together
        self._video_ms = 33
        self._photo = None
        self._video_item = None
        self._no_video = None          # reason why there is no video (shown on screen)
        self._no_video_global = None
        if cv2 is None:
            package = "opencv-python" if _MISSING == "cv2" else "pillow"
            self._no_video_global = f"NO VIDEO: missing package {package}  (pip install opencv-python pillow)"
            print("[Helmet]", self._no_video_global)
        self._no_video = self._no_video_global
        super().__init__(master, mission, owner, db_, on_close, routines)
        self.geometry(f"{self.real_width}x{self.real_height}")
        if cv2 is not None:
            self._next_frame()
        self.bind("<Left>", lambda e: self.cycle(-1))
        self.bind("<Right>", lambda e: self.cycle(1))
        self.bind("<Home>", lambda e: self.view(self.owner))
        self.bind("<Return>", lambda e: self.button_ack())
        self.bind("<KeyPress-v>", lambda e: self.button_view())
        self.bind("<KeyPress-a>", lambda e: self.button_go())
        self.focus_set()

    # ------------------------------------------------------------------ helpers
    def _block(self, x0, y0, x1, y1, edge=None, width_px=1):
        """Blocks with a transparent background (only the border is drawn, if requested)."""
        if edge:
            self.cv.create_rectangle(x0, y0, x1, y1, outline=edge, width=width_px)

    def _text(self, x, y, **kw):
        """Text with a dark shadow so it can be read over the video without a background."""
        shadow = dict(kw, fill="#000000")
        shadow.pop("tags", None)
        self.cv.create_text(x + 1, y + 1, **shadow)
        self.cv.create_text(x + 2, y + 2, **shadow)
        return self.cv.create_text(x, y, **kw)

    def _rounded(self, x0, y0, x1, y1, r, **kw):
        pts = [x0 + r, y0, x1 - r, y0, x1, y0, x1, y0 + r, x1, y1 - r, x1, y1,
               x1 - r, y1, x0 + r, y1, x0, y1, x0, y1 - r, x0, y0 + r, x0, y0]
        return self.cv.create_polygon(pts, smooth=True, **kw)

    # ------------------------------------------------------------------ drawing
    # ------------------------------------------------------------------ scale (several helmets at once)
    def _apply_scale(self, tag):
        # during a full redraw everything is scaled once at the end
        if self.hud_scale != 1.0 and (tag == "all" or not getattr(self, "_drawing", False)):
            self.cv.scale(tag, 0, 0, self.hud_scale, self.hud_scale)

    def draw(self):
        _SCALE[0] = self.hud_scale
        self._drawing = True
        try:
            self._draw_helmet()
        finally:
            _SCALE[0] = 1.0
            self._drawing = False
        self._apply_scale("all")

    def _draw_ecg(self):
        previous = _SCALE[0]
        _SCALE[0] = self.hud_scale
        try:
            super()._draw_ecg()
        finally:
            _SCALE[0] = previous
        self._apply_scale("ecg")

    def _draw_helmet(self):
        if not self._alive:
            return
        cv = self.cv
        cv.delete("all")
        W, H = self.WIDTH, self.HEIGHT
        t = self.mission.crew[self.viewed]

        self._scene(W, H)
        self._identity(t)
        self._link_time(W)
        self._state_and_crew(t, W)
        self._grid_lines(W / 2, H / 2 - 30)
        self._ring(t, 130, 334, 50)
        self._vitals_panel(t, 46, 396, 300, H - 44)
        self._o2_tanks(t)
        self._shortcuts(W, H)
        if self._no_video:
            cv.create_text(W - 70, H - 46, text=self._no_video, anchor="e", fill=AMBER, font=f(8, "bold"))
        if self.flash_on:
            cv.create_rectangle(0, 0, W, H, fill=RED, stipple="gray25", outline="")
        self._notifications(W)
        self._draw_ecg()
        self._risk_border()

    def _scene(self, W, H):
        """View through the visor: background video, or space, stars and the lunar surface."""
        cv = self.cv
        cv.configure(bg="#02060D")
        if self._video is not None:
            self._video_item = cv.create_image(0, 0, anchor="nw", image=self._photo) if self._photo else None
            cv.create_oval(-160, -130, W + 160, H + 130, outline="#000000", width=110)
            return
        for k in range(12):
            pitch = 6 + k * 2
            cv.create_rectangle(0, k * H / 12, W, (k + 1) * H / 12,
                                fill=f"#{pitch // 2:02x}{pitch:02x}{pitch + 10:02x}", outline="")
        for x, y, r in self.stars:
            cv.create_oval(x, y, x + r, y + r, fill="#9FB4C8", outline="")
        cv.create_oval(-W * 0.4, H * 0.72, W * 1.4, H * 2.6, fill="#252A31", outline="#3A414C", width=2)
        for cx, cy, r in ((W * 0.18, H * 0.86, 30), (W * 0.62, H * 0.9, 18), (W * 0.8, H * 0.82, 12)):
            cv.create_oval(cx - r * 2, cy - r / 2, cx + r * 2, cy + r / 2, fill="#1E2228", outline="")
        cv.create_oval(-160, -130, W + 160, H + 130, outline="#000000", width=110)

    def _identity(self, t):
        cv = self.cv
        self._block(64, 30, 330, 86)
        parts = t.name_.split()
        self._text(78, 50, text=f"EV{self.viewed + 1}", anchor="w", fill=HUD_DIM, font=f(12))
        self._text(114, 50, text=f"{parts[-1].upper()}, {parts[0][0]}.", anchor="w",
                    fill=WHITE, font=f(16, "bold"))
        is_you = self.viewed == self.owner
        self._text(78, 72, text="YOU" if is_you else f"CREWMATE · {t.role.upper()}", anchor="w",
                    fill=HUD if is_you else AMBER, font=f(9, "bold"))

    def _link_time(self, W):
        """UTC time and link with the ship: discreet."""
        cv = self.cv
        cx = W / 2
        no_link = self.mission.crew[self.owner].overall_state() == NO_SIGNAL
        if no_link:
            txt, col = "⇄ SHIP · NO LINK", RED
        else:
            clock = self.db.last_sent if self.db and self.db.last_sent else self.mission.clock()
            txt, col = f"⇄ SHIP · SENT {clock}", HUD_DIM
        self._text(cx, 40, text=f"{self.mission.clock()} UTC", fill=HUD_DIM, font=f(12, "bold"))
        self._text(cx, 58, text=txt, fill=col, font=f(9, "bold"))

    def _state_and_crew(self, t, W):
        """Large overall state, with the name of whoever is in alert when there is a broadcast."""
        x1 = W - 70
        eg = t.overall_state()
        col = COLOR_HUD[eg]
        queue_ = self.mission.broadcast_queue()
        self._text(x1 - 14, 48, text=HUD_WORD[eg], anchor="e", fill=col, font=f(20, "bold"))
        who = "YOU" if self.viewed == self.owner else t.name_.split()[0].upper()
        self._text(x1 - 14, 74, text=f"OVERALL STATE · {who}", anchor="e", fill=HUD_DIM,
                    font=f(9, "bold"))
        y = 84
        if queue_:
            d = queue_[0]
            affected = self.mission.crew[d.affected]
            name_ = "YOU" if d.affected == self.owner else affected.name_.upper()
            people = len({x.affected for x in queue_})
            extra = f" (+{people - 1})" if people > 1 else ""
            self._text(x1 - 14, 98, text=f"▲ ALERT: {name_}{extra}", anchor="e", fill=RED,
                        font=f(11, "bold"))
            y = 110
        self._crew_end = y

    def _grid_lines(self, x, y):
        cv = self.cv
        s = 10
        cv.create_polygon(x, y - s, x + s, y, x, y + s, x - s, y, outline=HUD_DIM, fill="")
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            cv.create_line(x + dx * 22, y + dy * 22, x + dx * 40, y + dy * 40, fill=HUD_DIM)

    def _ring(self, t, cx, cy, r):
        """Pulse circle: the ring changes color with the state; ECG with more contrast."""
        cv = self.cv
        e = t.indicator_state("hr")
        col = COLOR_HUD[e]
        cv.create_oval(cx - r, cy - r, cx + r, cy + r, fill="", outline=col, width=3)
        cv.create_oval(cx - r - 7, cy - r - 7, cx + r + 7, cy + r + 7, outline=col, width=1)
        for k in range(36):
            a = math.radians(k * 10)
            r1, r2 = r + 7, r + (12 if k % 3 == 0 else 10)
            cv.create_line(cx + r1 * math.cos(a), cy + r1 * math.sin(a),
                           cx + r2 * math.cos(a), cy + r2 * math.sin(a), fill=HUD_DIM)
        self._text(cx, cy + 18, text=format_value("hr", t.values_["hr"]), fill=col if e != OK else WHITE,
                    font=f(20, "bold"))
        self._text(cx, cy + 36, text="BPM", fill=HUD_DIM, font=f(8, "bold"))
        # ECG area (drawn by the inherited method)
        self.ecg_box = (cx - r + 8, cy - 34, cx + r - 8, cy + 2)
        self.ecg_color = col if e != OK else "#BFF4FF"
        self.ecg_hr = t.values_["hr"]

    # ------------------------------------------------------------------ vital signs panel
    def _vitals_panel(self, t, x0, y0, x1, y1):
        """Only HR, SpO₂, TEMP and PRES: short name and range on the left, value with unit on the right.
        The value changes color when it is not OK and the critical row is marked with a red border."""
        who = "YOU" if self.viewed == self.owner else t.name_.split()[0].upper()
        vitals = VITALS                      # always only HR, SpO₂, TEMP and PRES (critical ones are marked in red)
        y = y0 + 12
        self._text(x0 + 12, y, text=f"VITALS · {who}", anchor="w", fill=HUD_DIM, font=f(9, "bold"))
        y += 14
        row_height = min(44, (y1 - y) / len(vitals))
        for key in vitals:
            self._row(t, key, x0, y, x1, y + row_height)
            y += row_height

    def _row(self, t, key, x0, y0, x1, y1):
        ind = IND[key]
        e = t.indicator_state(key)
        col = COLOR_HUD[e]
        yc = (y0 + y1) / 2
        if e == ALERT:                        # highlight of the critical indicator (border only)
            self.cv.create_rectangle(x0 + 4, y0 + 2, x1 - 4, y1 - 2, outline=RED, width=2)
        value_col = col if e != OK else WHITE
        lo, hi = ind.range_
        d = ind.decimals
        range_ = f"≤{hi:.0f}" if ind.cumulative else f"{lo:.{d}f}–{hi:.{d}f}"
        self._text(x0 + 14, yc - 7, text=SHORT[key], anchor="w",
                    fill=col if e != OK else WHITE, font=f(12, "bold"))
        self._text(x0 + 14, yc + 10, text=range_, anchor="w", fill=HUD_DIM, font=f(8))
        xv = x0 + 150                          # values right next to the names
        self._text(xv, yc, text=format_value(key, t.values_[key]), anchor="e", fill=value_col,
                    font=f(20, "bold"))
        self._text(xv + 4, yc + 4, text=ind.unit, anchor="w", fill=HUD_DIM, font=f(9))

    # ------------------------------------------------------------------ tank notices
    def update_view(self):
        super().update_view()
        self._check_tanks()

    def _check_tanks(self):
        """Shows the ENGINE's tank notices for YOUR suit (it does not compute its own thresholds)."""
        m = self.mission
        if not self._current_shown:          # helmet opened late: notices that are still current
            self._current_shown = True
            for av in m.current_support_notices(self.owner):
                self._show_support(av)
        new_ones = m.support_notices[self._support_cursor:]
        self._support_cursor = len(m.support_notices)
        had = False
        for av in new_ones:
            if av.affected == self.owner:
                self._show_support(av)
                had = True
        if had:
            self.draw()

    def _show_support(self, av):
        if av.level == ALERT:
            self.notify(f"▲  {av.text}", RED)
            self.blink()
        else:
            self.notify(f"!  {av.text}", AMBER)

    # ------------------------------------------------------------------ oxygen tanks
    def _o2_tanks(self, t):
        """PLSS (main) and OPS (reserve). On top, the percentage of the tank in use."""
        no_signal = t.overall_state() == NO_SIGNAL
        viewed = None if no_signal else t.o2_tank
        backup = None if no_signal else t.o2_reserve
        if viewed is None:                          # no tank data: it is never assumed full
            text, col = "--", RED
        elif viewed > 0:
            text, col = f"{viewed:.0f}%", self._level_color(viewed, "PLSS")
        elif backup is None:
            text, col = "OPS --", RED
        else:                                          # PLSS depleted: the reserve is in use
            text, col = f"OPS {backup:.0f}%", self._level_color(backup, "OPS")
        self._text(982, 396, text=text, fill=WHITE if col == HUD else col, font=f(20, "bold"))
        self._tank(912, 420, 974, 592, viewed, "PLSS")      # both tanks the same size
        self._tank(990, 420, 1052, 592, backup, "OPS")

    def _level_color(self, level, label_):
        """OPS (reserve): red below 10 %, amber below 20 %. PLSS: amber below 20 %."""
        if level is None:
            return RED
        if label_ == "OPS" and level < 10:
            return RED
        if level < 20:
            return AMBER
        return HUD

    def _tank(self, x0, y0, x1, y1, level, label_):
        cv = self.cv
        col = self._level_color(level, label_)
        cv.create_rectangle(x0, y0, x1, y1, outline=col, width=3)
        if level is not None:
            ny = y1 - (y1 - y0) * level / 100
            if level > 0:
                cv.create_rectangle(x0 + 3, ny, x1 - 3, y1 - 3, fill=col, stipple="gray25", outline="")
            cv.create_line(x0, ny, x1, ny, fill=col, width=3)
        self._text((x0 + x1) / 2, (y0 + y1) / 2, text=label_, fill=WHITE, font=f(13, "bold"))

    # ------------------------------------------------------------------ shortcuts
    def _shortcuts(self, W, H):
        """Bottom bar: only the shortcuts that are useful right now."""
        d = self.current_notice()
        shortcuts = ["◀ ▶ · CREW MEMBER"]
        if self.viewed != self.owner:
            shortcuts.append("HOME · BACK TO YOU")
        if d is not None:
            shortcuts.append("ENTER · ACKNOWLEDGED")
            if d.affected != self.owner:
                shortcuts += ["A · I'M ON MY WAY", "V · VIEW DATA"]
        text = "     ".join(shortcuts)
        self._text(W / 2, H - 22, text=text, fill=WHITE if d is None else AMBER, font=f(11, "bold"))

    # ------------------------------------------------------------------ notifications
    def _notifications(self, W):
        """On the right, below the crew bar. In an emergency it brings the steps."""
        queue_ = self.mission.broadcast_queue()
        d = self.current_notice() or (queue_[0] if queue_ else None)
        if d is not None:
            key = ("emergency", d.id, d.attended_by)
        elif self.toast:
            key = ("toast", self.toast[0])
        else:
            self._banner_key = None
            return
        if key != self._banner_key:          # new notification: slides in
            self._banner_key = key
            self._banner_t0 = time.monotonic()
        prog = min(1.0, (time.monotonic() - self._banner_t0) / 0.35)
        prog = 1 - (1 - prog) ** 3
        width_px = 400
        x1 = W - 70 + (1 - prog) * (width_px + 80)
        x0 = x1 - width_px
        y0 = getattr(self, "_crew_end", 190) + 12
        if d is not None:
            y_end = self._emergency_panel(d, x0, y0, x1, expanded=self.current_notice() is d)
            if self.toast:                     # the notice (e.g. oxygen) appears below the emergency
                self._banner_toast(x0, y_end + 10, x1)
        else:
            self._banner_toast(x0, y0, x1)

    def _header(self, x0, y0, x1, icon_color, symbol, app):
        cv = self.cv
        self._rounded(x0 + 12, y0 + 10, x0 + 38, y0 + 36, 7, fill=icon_color, outline="")
        cv.create_text(x0 + 25, y0 + 23, text=symbol, fill="white", font=f(11, "bold"))
        cv.create_text(x0 + 48, y0 + 16, text=app, anchor="w", fill="#C3D0DB", font=f(8, "bold"))
        cv.create_text(x1 - 14, y0 + 16, text="now", anchor="e", fill="#C3D0DB", font=f(8))

    def _banner_toast(self, x0, y0, x1):
        cv = self.cv
        text, color = self.toast
        is_ok = color == GREEN
        is_red = color == RED
        body = text.lstrip("!✓★▲ ").replace(" · caution", "").strip()
        if ": " in body:
            name_, detail = body.split(": ", 1)
        else:
            name_, detail = body, ""
        y1 = y0 + 84
        self._rounded(x0, y0, x1, y1, 18, fill=BLOCK_BG, stipple="gray50", outline="")
        self._rounded(x0, y0, x1, y1, 18, fill="", outline=HUD if is_ok else (RED if is_red else AMBER),
                         width=3 if is_red else 2)
        if is_red:
            self._header(x0, y0, x1, "#E0302E", "⚠", "RED ALERT")
        else:
            self._header(x0, y0, x1, "#2E9E5B" if is_ok else "#C98A00", "✓" if is_ok else "!",
                           "NOTICE" if is_ok else "CAUTION")
        cv.create_text(x0 + 48, y0 + 40, text=name_, anchor="w", fill="white", font=f(12, "bold"),
                       width=x1 - x0 - 60)
        cv.create_text(x0 + 48, y0 + 63, text=detail, anchor="w", fill="#E3E9EF", font=f(11),
                       width=x1 - x0 - 60)

    def _emergency_panel(self, d, x0, y0, x1, expanded):
        """Compact emergency notice: name and title (and who is attending, if someone is already going)."""
        cv = self.cv
        t = self.mission.crew[d.affected]
        is_you = d.affected == self.owner
        title_ = protocol_for(t, is_you=is_you, key=d.key)[0]
        name_ = t.name_ + (" (YOU)" if is_you else f" ({t.role})")
        status = None
        if d.attended_by is not None:
            status = ("You are on your way to help" if d.attended_by == self.owner else
                      (f"{self.who(d.attended_by)} is on the way to help you" if is_you
                       else f"{self.who(d.attended_by)} is on the way to help"))
        y1 = y0 + 76 + (22 if status else 0)
        self._rounded(x0, y0, x1, y1, 18, fill="#120306", stipple="gray75", outline="")
        self._rounded(x0, y0, x1, y1, 18, fill="", outline=RED, width=3)
        queue_ = self.mission.broadcast_queue()
        others = len({x.affected for x in queue_}) - 1
        self._header(x0, y0, x1, "#E0302E", "⚠", "EMERGENCY" + (f" · +{others} IN QUEUE" if others > 0 else ""))
        cv.create_text(x0 + 48, y0 + 40, text=name_, anchor="w", fill="white", font=f(12, "bold"),
                       width=x1 - x0 - 60)
        cv.create_text(x0 + 48, y0 + 62, text=title_, anchor="w", fill="#FFD0D0", font=f(11, "bold"),
                       width=x1 - x0 - 60)
        if status:
            cv.create_text(x0 + 48, y0 + 84, text=status, anchor="w", fill=HUD, font=f(11, "bold"))
        return y1

    # ------------------------------------------------------------------ background video
    def _video_file(self, person):
        return VIDEOS_PER_PERSON[person % len(VIDEOS_PER_PERSON)]

    def _open_video(self, file_name):
        """Opens the video the first time it is needed. Returns its state or None (and the reason)."""
        if file_name in self._videos:
            return self._videos[file_name]
        path_ = os.path.join(_FOLDER, file_name)
        v = None
        if not os.path.exists(path_):
            reason = f"NO VIDEO: could not find {file_name} in {_FOLDER}"
        else:
            cap = cv2.VideoCapture(path_)
            n = int(cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0) if cap.isOpened() else 0
            if cap.isOpened() and n > 0:
                v = {"cap": cap, "fps": cap.get(cv2.CAP_PROP_FPS) or 24, "n": n, "pos": -1, "reason": None}
            else:
                reason = f"NO VIDEO: could not open {file_name}"
        if v is None:
            print("[Helmet]", reason)
            v = {"cap": None, "reason": reason}
        self._videos[file_name] = v
        return v

    def _next_frame(self):
        if not self._alive:
            return
        v = self._open_video(self._video_file(self.viewed))
        if v["cap"] is None:                       # this person has no video: space is drawn
            change = self._video is not None or self._no_video != v["reason"]
            self._video, self._photo, self._no_video = None, None, v["reason"]
            if change:
                self.draw()
            self.after(250, self._next_frame)
            return
        person_changed = self._video is not v["cap"]
        self._video, self._no_video = v["cap"], None
        # frame due NOW according to the common clock (the video kept running even when not visible)
        target = int((time.monotonic() - self._video_t0) * v["fps"]) % v["n"]
        jump = (target - v["pos"]) % v["n"]
        frame_ = None
        if jump == 0 and not person_changed:
            pass                                    # no new frame due yet
        else:
            cap = v["cap"]
            if v["pos"] < 0 or jump > v["fps"]:     # very far (or first time): seek the frame
                cap.set(cv2.CAP_PROP_POS_FRAMES, target)
            elif jump > 1:
                for _ in range(jump - 1):           # close: skip the intermediate frames
                    cap.grab()
            ok, frame_ = cap.read()
            if not ok:                               # finished: start over (loop)
                cap.set(cv2.CAP_PROP_POS_FRAMES, 0)
                target = 0
                ok, frame_ = cap.read()
            v["pos"] = target if ok else -1
            if not ok:
                frame_ = None
        if frame_ is not None:
            frame_ = cv2.resize(frame_, (self.real_width, self.real_height))
            frame_ = cv2.cvtColor(frame_, cv2.COLOR_BGR2RGB)
            frame_ = cv2.convertScaleAbs(frame_, alpha=VIDEO_BRIGHTNESS)
            self._photo = ImageTk.PhotoImage(Image.fromarray(frame_))
            if self._video_item is None or person_changed:
                self.draw()
            else:
                self.cv.itemconfigure(self._video_item, image=self._photo)
        # with several helmets open each one lowers its frames per second so the PC is not overloaded
        helmets = sum(isinstance(o, Helmet) for o in getattr(self.ship, "wristbands", [])) or 1
        self._video_ms = 33 if helmets == 1 else min(100, 20 * helmets)
        self.after(self._video_ms, self._next_frame)

    def close_window(self):
        for v in self._videos.values():
            if v.get("cap") is not None:
                v["cap"].release()
        self._videos.clear()
        self._video = None
        super().close_window()

    def at_risk(self):
        """YOU are at risk: your own red alert / no signal, or OPS reserve below 10 %."""
        t = self.mission.crew[self.owner]
        if any(d.affected == self.owner for d in self.mission.broadcast_queue()):
            return True
        return t.support_state() == ALERT

    def _risk_border(self):
        """Blinking red border (only on the helmet of the person at risk; the others only see the notice)."""
        cv = self.cv
        cv.delete("risk")
        mine = [d for d in self.mission.broadcast_queue() if d.affected == self.owner]
        silenced = bool(mine) and all(self.mission.is_silenced(d) for d in mine)
        # silenced: the red border stays steady (no blinking) while the silence lasts
        if self.at_risk() and (silenced or self.flash_on or int(time.monotonic() * 2) % 2 == 0):
            W, H = self.WIDTH, self.HEIGHT
            cv.create_rectangle(6, 6, W - 6, H - 6, outline=RED, width=12 if self.flash_on else 8, tags="risk")
            self._apply_scale("risk")

    def _animate(self):
        """Besides the ECG: banner animation and blinking red border if you are at risk."""
        if self._alive and self._banner_key and time.monotonic() - self._banner_t0 < 0.4:
            self.draw()
        if self._alive:
            self._risk_border()
        super()._animate()
