def validate(key, value):
    """Returns (float_value_or_None, quality). Never turns bad data into 'normal' data."""
    if value is None:
        return None, Q_NO_DATA
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None, Q_INVALID
    v = float(value)
    if math.isnan(v) or math.isinf(v):
        return None, Q_INVALID
    lo, hi = IND[key].contract if key in IND else (None, None)
    if (lo is not None and v < lo) or (hi is not None and v > hi):
        return None, Q_OUT_OF_CONTRACT
    return v, Q_OK


