def severity(key):
    """Lower number = more severe. Total signal loss first, then life support."""
    if key == SIGNAL:
        return 0
    if key == OPS:
        return 1
    return 2 + ALERT_PRIORITY.index(key)


def address(key, value):
    """'low' or 'high' depending on which side of the range the value left."""
    if key == OPS:
        return "low"
    ind = IND[key]
    if value is None:
        return "high" if ind.critical[0] is None else "low"
    return "low" if value < ind.range_[0] else "high"


def protocol_for(t, is_you=False, key=None, value=None):
    """(title, problem, steps) to handle an alarm. 2nd person if is_you, otherwise 3rd person.
    value: the one that triggered the alarm (if not given, the current one is used)."""
    name_ = t.name_.split()[0]
    if key == SIGNAL or (key is None and t.overall_state() == NO_SIGNAL):
        if is_you:
            return ("Signal lost",
                    "Your wristband stopped sending data to the ship.",
                    ["Check that the sensor is well placed and has battery.",
                     "Tell the ship over the radio that you are OK.",
                     "If it is not fixed, swap the wristband for the spare one.",
                     "Tell the medical officer if you feel unwell."])
        return ("Signal lost",
                f"'s wristband stopped sending data. {name_}",
                [f"Call {name_} over the radio.",
                 "If they do not answer, go to their location (buddy check).",
                 "Check that their sensor is well placed and has battery.",
                 "Tell the ship if you cannot make contact."])
    if key is None:
        key = next((c for c in ALERT_PRIORITY if t.indicator_state(c) == ALERT), None)
    if key is None:
        return ("Check", "Check your state." if is_you else f"Check on {name_}.",
                [NEXT_STEP[CAUTION]])
    if key == OPS:
        v = t.o2_reserve if value is None else value
        value_txt = "--" if v is None else f"{v:.0f} %"
        title_, steps_you, steps_other = PROTOCOLS[(OPS, "low")]
        problem = f"OPS reserve (you): {value_txt}." if is_you else f"{name_}'s OPS reserve: {value_txt}."
        return title_, problem, steps_you if is_you else steps_other
    ind = IND[key]
    v = t.values_.get(key) if value is None else value
    key_ = (key, address(key, v))
    if key_ not in PROTOCOLS:
        key_ = next(k for k in PROTOCOLS if k[0] == key)
    title_, steps_you, steps_other = PROTOCOLS[key_]
    value_txt = f"{format_value(key, v)} {ind.unit}"
    short = ind.name_.split(" (")[0]
    problem = f"{short} (you): {value_txt}." if is_you else f"{name_}'s {short}: {value_txt}."
    return title_, problem, steps_you if is_you else steps_other


def status_of(key, value, quality=Q_OK):
    """Classifies a value according to the demo rules. Bad data never counts as 'within range'."""
    if quality == Q_STALE or quality == Q_NO_DATA:
        return NO_SIGNAL
    if quality in (Q_INVALID, Q_OUT_OF_CONTRACT):
        return INVALID
    v, qual = validate(key, value)
    if qual == Q_NO_DATA:
        return NO_SIGNAL
    if qual != Q_OK:
        return INVALID
    ind = IND[key]
    v = round(v, ind.decimals)   # classifies the same way as shown on screen
    lo, hi = ind.range_
    clo, chi = ind.critical
    if (clo is not None and v < clo) or (chi is not None and v > chi):
        return ALERT
    if v < lo or v > hi:
        return CAUTION
    return OK


def worst_state(statuses):
    return max(statuses, key=lambda e: STATE_ORDER[e]) if statuses else OK


def format_value(key, value):
    if value is None:
        return "--"
    try:
        return f"{value:.{IND[key].decimals}f}"
    except (TypeError, ValueError):
        return "--"


def translation(t, key, is_you=True):
    """One line in plain language. E.g.: "Your pulse is high: rest 10 min and breathe slowly"."""
    ind = IND[key]
    value = t.values_.get(key)
    e = t.indicator_state(key)
    subject = f"Your {ind.simple}" if is_you else f"{t.name_.split()[0]}'s {ind.simple}"
    if e in (NO_SIGNAL, INVALID):
        return f"{subject}: {QUALITY_TEXT[t.quality.get(key, Q_NO_DATA)].lower()}. {NEXT_STEP[e]}"
    if e == OK:
        return f"{subject} is fine. {ind.explanation}"
    low = value < ind.range_[0]
    word = "low" if low else "high"
    if is_you:
        action = ind.actions[0 if low else 1] or "rest 10 min and measure again"
        if e == ALERT and "medical officer" not in action:
            action += ". Tell the medical officer now"
    else:
        action = ("go help them and tell the medical officer" if e == ALERT
                  else "ask them how they are")
    return f"{subject} is {word}: {action}."


