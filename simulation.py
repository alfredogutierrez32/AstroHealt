@dataclass
class CrewMember:
    name_: str
    role: str
    initials: str
    bias: dict
    scenario: str = "Stable"
    values_: dict = field(default_factory=dict)       # key -> validated float or None
    quality: dict = field(default_factory=dict)       # key -> data quality
    origin: dict = field(default_factory=dict)        # key -> origin ("simulation", real source...)
    t_measured: dict = field(default_factory=dict)    # key -> measurement instant (UTC) or None
    history: dict = field(default_factory=dict)
    mood: int = 4                                    # mood GENERATED by the simulation (1-5)
    reported_mood: object = None                    # mood REPORTED by the person (1-5) or None
    reported_mood_min: object = None                # simulated minute of the last check-in
    mood_history: list = field(default_factory=list)
    o2_tank: object = 100.0                         # PLSS (main), %; None if there is no data
    o2_reserve: object = 100.0                       # OPS (reserve), %; None if there is no data
    pseudonym: str = ""                               # pseudonymized identifier (for real data)
    MAX_HIST = 240

    def __post_init__(self):
        base = SCENARIOS["Stable"]
        for i in INDICATORS:
            v = INITIAL_RAD + self.bias.get(i.key, 0) if i.cumulative else base[i.key] + self.bias.get(i.key, 0)
            self.values_[i.key] = v
            self.quality[i.key] = Q_OK
            self.origin[i.key] = "simulation"
            self.t_measured[i.key] = None
            self.history[i.key] = [v]
        self._accumulated = {i.key: self.values_[i.key] for i in INDICATORS if i.cumulative}
        self.mood_history.append(self.mood)

    # ---- simulation ----
    def step(self, rng):
        target = SCENARIOS[self.scenario]
        for i in INDICATORS:
            if i.cumulative:
                rhythm = (target or SCENARIOS["Stable"])[i.key]
                self._accumulated[i.key] += max(0.0, rng.gauss(rhythm, rhythm * 0.2))
                v = None if target is None else self._accumulated[i.key]
            elif target is None:
                v = None
            else:
                current_ = self.values_.get(i.key)
                goal = target[i.key] + self.bias.get(i.key, 0)
                if current_ is None:
                    current_ = goal
                v = current_ + (goal - current_) * 0.25 + rng.gauss(0, i.noise)
                if i.key == "spo2":
                    v = min(v, 100.0)
                v = max(v, 0.0)
            self.values_[i.key] = v
            self.quality[i.key] = Q_OK if v is not None else Q_NO_DATA
            self.origin[i.key] = "simulation"
            self._history(i.key, v)
        # simulated life support: the PLSS only goes down; when it runs out the OPS reserve is used
        consumption = O2_CONSUMPTION.get(self.scenario, 0.12)
        if self.o2_tank is not None and self.o2_tank > 0:
            self.o2_tank = max(0.0, self.o2_tank - consumption)
        elif self.o2_reserve is not None:
            self.o2_reserve = max(0.0, self.o2_reserve - consumption * O2_RESERVE_FACTOR)
        # simulated mood (does not touch the mood reported by the person)
        mood_goal = SCENARIO_MOOD.get(self.scenario)
        if mood_goal is not None and self.mood != mood_goal and rng.random() < 0.08:
            self.mood += 1 if mood_goal > self.mood else -1
        self.mood_history.append(self.mood)
        if len(self.mood_history) > self.MAX_HIST:
            del self.mood_history[0]

    def _history(self, key, v):
        h = self.history[key]
        h.append(v)
        if len(h) > self.MAX_HIST:
            del h[0]

    # ---- real data (REPLAY / LIVE modes) ----
    def apply_measurement(self, key, value, origin, t_measured=None, quality=None):
        """Stores an already normalized measurement. Validates again: never accepts bad data as good."""
        v, qual = validate(key, value)
        if quality is not None and quality != Q_OK:
            v, qual = None, quality
        self.values_[key] = v
        self.quality[key] = qual
        self.origin[key] = origin
        self.t_measured[key] = t_measured
        self._history(key, v)

    def mark_stale(self, key):
        self.values_[key] = None
        self.quality[key] = Q_STALE

    def clear_for_real_data(self):
        """When switching to a real-data mode: everything is 'not available' until measurements arrive."""
        for i in INDICATORS:
            self.values_[i.key] = None
            self.quality[i.key] = Q_NO_DATA
            self.origin[i.key] = "no source"
            self.t_measured[i.key] = None
        self.o2_tank = None
        self.o2_reserve = None

    def record_mood(self, value, minute=None):
        """Mood check-in done by the person themselves (1 = very bad, 5 = very good).
        Stored separately from the simulated mood."""
        self.reported_mood = max(1, min(5, int(value)))
        self.reported_mood_min = minute

    # ---- states ----
    def indicator_state(self, key):
        return status_of(key, self.values_.get(key), self.quality.get(key, Q_OK))

    def overall_state(self):
        """HEALTH state (life support is separate, see support_state)."""
        return worst_state([self.indicator_state(i.key) for i in INDICATORS])

    def total_signal_lost(self):
        return all(self.quality.get(i.key) in (Q_NO_DATA, Q_STALE) for i in INDICATORS)

    def criticals(self):
        """Indicators in red alert; SIGNAL if ALL signal was lost."""
        if self.total_signal_lost():
            return {SIGNAL}
        return {i.key for i in INDICATORS if self.indicator_state(i.key) == ALERT}

    def availability(self):
        """key -> data quality (technical dimension, separate from the physiological state)."""
        return {i.key: self.quality.get(i.key, Q_NO_DATA) for i in INDICATORS}

    def support_state(self):
        """LIFE SUPPORT state (tanks). Independent from the health state."""
        if self.o2_tank is None and self.o2_reserve is None:
            return NO_SIGNAL
        if self.o2_tank is not None and self.o2_tank > 0:
            return CAUTION if self.o2_tank < 20 else OK
        if self.o2_reserve is None:
            return NO_SIGNAL
        return ALERT if self.o2_reserve < 10 else CAUTION

    def key_state(self, key):
        if key == SIGNAL:
            return NO_SIGNAL if self.total_signal_lost() else OK
        if key == OPS:
            if self.o2_tank is not None and self.o2_tank > 0:
                return OK
            if self.o2_reserve is None:
                return NO_SIGNAL
            return ALERT if self.o2_reserve < 10 else (CAUTION if self.o2_reserve < 20 else OK)
        return self.indicator_state(key)

    def key_value(self, key):
        if key == OPS:
            return self.o2_reserve
        if key == SIGNAL:
            return None
        return self.values_.get(key)


