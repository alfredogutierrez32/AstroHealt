    # ---------------- mode ----------------
    def set_mode(self, mode):
        if mode not in MODES:
            raise ValueError(f"Unknown mode: {mode}")
        self.mode = mode
        if mode != MODE_SIMULATION:
            for t in self.crew:
                t.clear_for_real_data()
            self._last_avail = [t.availability() for t in self.crew]
        self._event("Ship", f"Mode: {mode}", OK, category="config")

    # ---------------- time ----------------
    def clock(self):
        return self.clock_.strftime("%H:%M")

    def sim_time(self):
        return self.clock_.isoformat()

    def step(self):
        """Advances 1 simulated minute. In real-data modes no values are generated."""
        self.minutes_ += 1
        self.clock_ += timedelta(minutes=1)
        for i, t in enumerate(self.crew):
            if self.mode == MODE_SIMULATION:
                t.step(self.rng)
            self.evaluate(i)
        self.events = self.events[-60:]

    def evaluate(self, i):
        """Checks states, availability, life support and alarms for crew member i."""
        t = self.crew[i]
        e = t.overall_state()
        if e != self._last_state[t.name_]:
            self._event(t.name_, f"changed to {STATE_TEXT[e]}", e)
            self._last_state[t.name_] = e
        self._check_availability(i, t)
        self._check_support(i, t)
        self._check_broadcasts(i, t)

    # ---------------- records ----------------
    def _event(self, name_, text, status, incident=None, category="health"):
        ev = LogEvent(self.clock(), name_, text, status, self.minutes_, self.sim_time(),
                    self.utc_clock().isoformat(), incident, category)
        self.events.append(ev)
        self.total_events.append(ev)

    def _notice(self, d, receiver, action):
        t = self.crew[d.affected]
        receiver_name = ("Whole crew" if receiver is None else
                           "Ship" if receiver == "ship" else self.crew[receiver].name_)
        self.total_notices.append(Notice(self.clock(), t.name_, d.indicator_name(), receiver_name, action,
                                         self.minutes_, self.sim_time(), self.utc_clock().isoformat(),
                                         d.incident))

    # ---------------- availability (technical) ----------------
    def _check_availability(self, i, t):
        avail = t.availability()
        before = self._last_avail[i]
        if not t.total_signal_lost():          # total loss is handled by the SIGNAL alarm
            for key, qual in avail.items():
                if qual != before.get(key):
                    ind = IND[key]
                    if qual == Q_OK:
                        self._event(t.name_, f"data for {ind.name_} available again", OK, category="signal")
                    else:
                        self._event(t.name_, f"{ind.name_}: {QUALITY_TEXT[qual].lower()}",
                                     INVALID if qual in (Q_INVALID, Q_OUT_OF_CONTRACT) else NO_SIGNAL,
                                     category="signal")
        self._last_avail[i] = avail

    # ---------------- life support (tanks) ----------------
    @staticmethod
    def _current_thresholds(t):
        """Oxygen levels already reached: PLSS 50/30/10/5/0 % plus start and every 10 % of the OPS."""
        plss, ops = t.o2_tank, t.o2_reserve
        u = set()
        if plss is not None:
            u |= {f"plss{n}" for n in PLSS_LEVELS if plss <= n}
            if plss <= 0 and ops is not None:
                u |= {f"ops{n}" for n in OPS_LEVELS if ops <= n}
        return u

    def _support_text(self, t, threshold):
        """(level, text) of a threshold notice."""
        n = _threshold_level(threshold)
        if threshold == "plss0":
            return CAUTION, "PLSS depleted: starting OPS emergency reserve"
        if threshold.startswith("plss"):        # the text says the REAL value (not the threshold)
            return CAUTION, f"PLSS at {t.o2_tank:.0f} %: {self.time_left(t)}"
        if n <= OPS_RED:
            return ALERT, f"OPS reserve at {t.o2_reserve:.0f} %: {self.time_left(t)} · return to the ship"
        return CAUTION, f"OPS reserve at {t.o2_reserve:.0f} %: {self.time_left(t)}"

    @staticmethod
    def _deepest(thresholds):
        """The lowest threshold reached for each tank (so notices are not repeated on long advances)."""
        plss = [u for u in thresholds if u.startswith("plss")]
        ops = [u for u in thresholds if u.startswith("ops")]
        res = []
        if plss:
            res.append(min(plss, key=lambda u: _threshold_level(u)))
        if ops:
            res.append(min(ops, key=lambda u: _threshold_level(u)))
        return res

    def _check_support(self, i, t):
        """Generates tank notices in the ENGINE (does not depend on the helmet being open).
        If several levels are crossed in a single step (+1 h advance), only the lowest of each
        tank is notified; the start of the OPS reserve is always notified."""
        current_ = self._current_thresholds(t)
        new_ones = current_ - self._support_threshold[i]
        notify_ = self._deepest(new_ones)
        if "plss0" in new_ones and "plss0" not in notify_:
            notify_.insert(0, "plss0")
        notify_.sort(key=lambda u: (not u.startswith("plss"), -_threshold_level(u)))   # PLSS first, then OPS
        for u in notify_:
            self._support(i, *self._support_text(t, u), threshold=u, t=t)
        self._support_threshold[i] = current_

    def _support(self, i, level, text, threshold=None, t=None):
        value = None
        if t is not None and threshold:
            value = t.o2_tank if threshold.startswith("plss") else t.o2_reserve
        time_ = self.time_left(t) if t is not None else None
        self.support_notices.append(SupportNotice(i, level, text, threshold, value, time_))
        self._event(self.crew[i].name_, f"Life support: {text}", level, category="support")

    def time_left(self, t):
        """Text with the approximate oxygen time left (based on the scenario's simulated consumption)."""
        consumption = O2_CONSUMPTION.get(t.scenario, 0.12)
        if self.mode != MODE_SIMULATION:
            return "time left not available"
        if t.o2_tank is not None and t.o2_tank > 0:
            m = int(t.o2_tank / consumption)
        elif t.o2_reserve is not None:
            m = int(t.o2_reserve / (consumption * O2_RESERVE_FACTOR))
        else:
            return "no data"
        return f"≈ {m // 60} h {m % 60:02d} min left" if m >= 60 else f"≈ {m} min left"

    def current_support_notices(self, i):
        """Tank notice that is STILL current now (to show it when the helmet is opened late)."""
        t = self.crew[i]
        deep = self._deepest(self._current_thresholds(t))
        if not deep:
            return []
        u = deep[-1]                     # if there is already an OPS level, that one wins
        value = t.o2_tank if u.startswith("plss") else t.o2_reserve
        return [SupportNotice(i, *self._support_text(t, u), u, value, self.time_left(t))]

    # ---------------- alarms ----------------
    def _check_broadcasts(self, i, t):
        """Lifecycle: critical -> (caution) -> within range. Only 'within range' closes the alarm."""
        criticals = t.criticals()
        if t.key_state(OPS) == ALERT:
            criticals = criticals | {OPS}
        actives = {c for (a, c) in self._active if a == i}
        if SIGNAL in criticals:
            criticals = criticals | actives      # without signal we do not know whether the rest improved
        for key in sorted(criticals - actives, key=severity):
            self._new_broadcast(i, t, key)
        for key in actives - criticals:
            d = self._active[(i, key)]
            e = t.key_state(key)
            if e == OK:
                self._resolve(i, key)
            elif e == ALERT:                                    # (should not happen: it would be in criticals)
                continue
            elif e == CAUTION and d.phase == PHASE_CRITICAL:
                d.phase = PHASE_CAUTION
                self.critical_exits.append(d)
                self._event(t.name_, f"{d.indicator_name()} left critical state (still in caution)",
                             CAUTION, d.incident)
                self._notice(d, None, "left critical")
            # NO_SIGNAL / INVALID for that indicator: the alarm stays open (no evidence of improvement)
        for key in actives & criticals:                          # back to red from yellow
            d = self._active[(i, key)]
            if d.phase == PHASE_CAUTION and t.key_state(key) == ALERT:
                d.phase = PHASE_CRITICAL
                d.last_notice = self.real_clock()
                d.cycle_acks.clear()
                d.repetitions += 1
                self.silenced.discard(d.id)                      # got worse again: it sounds again
                self._event(t.name_, f"{BROADCAST_PREFIX}: {d.indicator_name()} back to critical state",
                             ALERT, d.incident)
                self._notice(d, None, "back to critical")

    def _new_broadcast(self, i, t, key):
        now_ = self.real_clock()
        d = Broadcast(self._next_id, i, key, t.key_value(key), self.clock(), self.minutes_, now_, now_)
        self._next_id += 1
        self.broadcasts.append(d)
        self._active[(i, key)] = d
        self._event(t.name_, f"{BROADCAST_PREFIX}: {d.indicator_name()} {d.value_text()} "
                               f"· notice to the whole crew", ALERT if key != SIGNAL else NO_SIGNAL,
                     d.incident, category="support" if key == OPS else "health")
        # "received" only if there is an open wristband showing it; otherwise it says it is unconfirmed
        for k in range(len(self.crew)):
            if k in self.receivers:
                d.received.add(k)
                self._notice(d, k, "received")
            else:
                self._notice(d, k, "unconfirmed (no open wristband)")

    def _resolve(self, i, key):
        d = self._active.pop((i, key))
        d.resolved = True
        d.resolved_time = self.clock()
        self.resolutions.append(d)
        self._event(self.crew[i].name_, f"{d.indicator_name()} back within range", OK, d.incident)
        self._notice(d, None, "back within range")

    def check_repetitions(self):
        """Repeats every REPEAT_S the CRITICAL alarms nobody has ATTENDED (even if they were acknowledged).
        Each repetition resets the cycle's ACKNOWLEDGED. After ESCALATE_AFTER repetitions it escalates to the ship."""
        now_ = self.real_clock()
        repeated = []
        for d in self._active.values():
            if d.phase == PHASE_CRITICAL and d.attended_by is not None and now_ - d.last_notice >= REPEAT_S:
                # someone is already on the way: the alarm keeps sounding ONLY for the person in red
                # (it no longer sounds for the others) and it is not escalated, since someone is attending
                d.last_notice = now_
                d.repetitions += 1
                d.cycle_acks.discard(d.affected)
                repeated.append(d)
                self._notice(d, d.affected, f"repetition {d.repetitions} (person in red only)")
                continue
            if d.phase == PHASE_CRITICAL and d.attended_by is None and now_ - d.last_notice >= REPEAT_S:
                d.last_notice = now_
                d.repetitions += 1
                d.cycle_acks.clear()
                repeated.append(d)
                self._notice(d, None, f"repetition {d.repetitions}")
                if d.repetitions >= ESCALATE_AFTER and not d.escalated:
                    d.escalated = True
                    self._event(self.crew[d.affected].name_,
                                 f"{BROADCAST_PREFIX}: {d.indicator_name()} ESCALATED to the ship (nobody is attending)",
                                 ALERT, d.incident)
                    self._notice(d, "ship", "escalated")
        return repeated

    def broadcast_queue(self):
        """Open alarms: critical ones first, by severity and age."""
        return sorted(self._active.values(),
                      key=lambda d: (d.phase != PHASE_CRITICAL, d.severity, d.t_start))

    # ---------------- silence alarms (from the wristband or the phone) ----------------
    def silence(self, receiver):
        """Pauses for SILENCE_S seconds the sound, blinking and voice of the RED alarms open now.
        It does not resolve or hide them: they stay in the strip, keep repeating/escalating in the log,
        and a NEW alarm (or one that goes back to critical) sounds normally. Returns True if it silenced anything."""
        critical = [d for d in self.broadcast_queue() if d.phase == PHASE_CRITICAL and not d.resolved]
        if not critical:
            return False
        self.silenced = {d.id for d in critical}
        self.silence_until = self.real_clock() + SILENCE_S
        self.silences += 1
        who = "Ship" if receiver == "ship" else self.crew[receiver].name_
        mins = int(SILENCE_S // 60)
        for d in critical:
            self._notice(d, receiver, f"silenced the alarm {mins} min")
            self._event(self.crew[d.affected].name_,
                        f"{who.split()[0]} silenced the {d.indicator_name()} alarm "
                        f"for {mins} min (still active)", ALERT, d.incident)
        return True

    def silence_left(self):
        """Seconds left in the silence (0 if none)."""
        if not self.silenced:
            return 0.0
        return max(0.0, self.silence_until - self.real_clock())

    def is_silenced(self, d):
        return d.id in self.silenced and self.silence_left() > 0

    def broadcast(self, id_):
        return next((d for d in self.broadcasts if d.id == id_), None)

    def _response(self, d, receiver):
        if receiver != d.affected and d.response_secs is None:
            d.response_secs = self.real_clock() - d.t_start
            d.who_responded = receiver
            self._event(self.crew[d.affected].name_,
                         f"{BROADCAST_PREFIX}: first response from "
                         f"{self.crew[receiver].name_.split()[0]} in {d.response_secs:.0f} s",
                         ALERT, d.incident)

    def acknowledged(self, id_, receiver):
        """ACKNOWLEDGED (ack). Returns seconds since the START of the incident if it is a new
        response in this cycle; None if they had already responded in this cycle."""
        d = self.broadcast(id_)
        if d is None or receiver in d.cycle_acks:
            return None
        d.cycle_acks.add(receiver)
        first_time = receiver not in d.acks
        d.acks.add(receiver)
        self._notice(d, receiver, "acknowledged")
        self._response(d, receiver)
        return (self.real_clock() - d.t_start) if first_time else None

    def record_on_the_way(self, helper, d):
        """Notification "X is on the way to help Y" (one per I'M ON MY WAY press)."""
        self.on_the_way.append(OnTheWay(helper, d.affected, self.clock(), d.incident))

    def attend(self, id_, receiver):
        """I'M ON MY WAY (attention). True if they were the first to attend."""
        d = self.broadcast(id_)
        if d is None or d.resolved or receiver == d.affected:
            return False
        if d.attended_by is not None:
            return False
        self._notice(d, receiver, "on my way")
        self._response(d, receiver)
        d.attended_by = receiver
        d.cycle_acks.add(receiver)
        d.acks.add(receiver)
        self._event(self.crew[d.affected].name_,
                     f"{BROADCAST_PREFIX}: {self.crew[receiver].name_.split()[0]} is attending them",
                     ALERT, d.incident)
        return True

    # ---------------- real data ----------------
    def _by_pseudonym(self, person):
        return next((i for i, t in enumerate(self.crew) if t.pseudonym == person), None)

    def apply_measurement(self, m):
        """Applies a sources.Measurement to the crew member with that pseudonym (real-data modes only)."""
        if self.mode == MODE_SIMULATION:
            return False                      # real data is never mixed with the simulation
        i = self._by_pseudonym(m.person)
        if i is None:
            self._event("Ship", f"measurement ignored: person '{m.person}' not registered", INVALID,
                         category="signal")
            return False
        t = self.crew[i]
        if m.indicator == "plss":
            t.o2_tank = m.value if m.quality == Q_OK else None
        elif m.indicator == "ops":
            t.o2_reserve = m.value if m.quality == Q_OK else None
        elif m.indicator in IND:
            t.apply_measurement(m.indicator, m.value, m.source, m.t_measured,
                               quality=None if m.quality == Q_OK else
                               (Q_INVALID if m.quality not in (Q_NO_DATA, Q_OUT_OF_CONTRACT) else m.quality))
        else:
            return False
        self.evaluate(i)
        return True

    def mark_stale(self, person, indicator):
        i = self._by_pseudonym(person)
        if i is None or indicator not in IND:
            return False
        t = self.crew[i]
        if t.quality.get(indicator) == Q_STALE:
            return False
        t.mark_stale(indicator)
        self.evaluate(i)
        return True

    # ---------------- helpers ----------------
    def set_scenario(self, index_, scenario):
        self.crew[index_].scenario = scenario

    def random_scenario(self):
        weights_ = [0.55, 0.25, 0.1, 0.1]
        for t in self.crew:
            t.scenario = self.rng.choices(SCENARIO_NAMES, weights_)[0]

    def summary(self):
        tally = {OK: 0, CAUTION: 0, ALERT: 0, NO_SIGNAL: 0, INVALID: 0}
        for t in self.crew:
            tally[t.overall_state()] += 1
        return tally
